/**
 * ВЕСЬ контент игры находится в этом файле.
 * Правь тексты, вопросы, ответы и пути к фото прямо здесь — код трогать не нужно.
 */

export interface QuizQuestion {
  question: string;
  options: string[];
  /** Индекс правильного ответа в массиве options (с нуля) */
  correctIndex: number;
  /** Комментарий, который показывается после правильного ответа */
  afterText?: string;
}

export interface MemoryPair {
  emoji: string;
  label: string;
}

interface StageBase {
  id: string;
  /** Эмодзи-иконка этапа на карте путешествия */
  emoji: string;
  title: string;
  /** Короткая подпись на карте */
  subtitle: string;
  /** Вступительный текст перед этапом */
  intro: string;
  /** Фрагмент финального письма, который открывается после прохождения */
  letterFragment: string;
}

export interface QuizStage extends StageBase {
  type: 'quiz';
  questions: QuizQuestion[];
}

export interface MemoryStage extends StageBase {
  type: 'memory';
  pairs: MemoryPair[];
}

export interface RiddleStage extends StageBase {
  type: 'riddle';
  riddle: string;
  /** Ответ (регистр не важен) */
  answer: string;
  /** Подсказки, открываются по очереди */
  hints: string[];
}

export interface PuzzleStage extends StageBase {
  type: 'puzzle';
  /**
   * Путь к фото относительно public/, например '/photos/us.jpg'.
   * Положи фото в папку public/photos/ и укажи путь здесь.
   * Если фото нет — покажется красивая иллюстрация-заглушка.
   */
  photo?: string;
  caption: string;
}

export type Stage = QuizStage | MemoryStage | RiddleStage | PuzzleStage;

